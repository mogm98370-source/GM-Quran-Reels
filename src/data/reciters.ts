/**
 * Returns full direct URL for a full-surah MP3 file
 */
export function getSurahAudioUrl(reciter: Reciter, surahNumber: number): string {
  const padded = String(surahNumber).padStart(3, '0');
  // If server url is MP3Quran (e.g. server8.mp3quran.net/rifai)
  if (reciter.serverUrl.includes('mp3quran.net')) {
    return `${reciter.serverUrl}/${padded}.mp3`;
  }
  // If fallback is MP3Quran, we can use it as well
  if (reciter.fallbackServerUrl && reciter.fallbackServerUrl.includes('mp3quran.net')) {
    return `${reciter.fallbackServerUrl}/${padded}.mp3`;
  }
  // Default EveryAyah full surah or first ayah
  return `${reciter.serverUrl}/${padded}001.mp3`;
}

/**
 * Returns fallback direct URL for surah
 */
export function getSurahAudioFallbackUrl(reciter: Reciter, surahNumber: number): string {
  const padded = String(surahNumber).padStart(3, '0');
  if (reciter.fallbackServerUrl) {
    if (reciter.fallbackServerUrl.includes('mp3quran.net')) {
      return `${reciter.fallbackServerUrl}/${padded}.mp3`;
    }
    return `${reciter.fallbackServerUrl}/${padded}001.mp3`;
  }
  return `https://server8.mp3quran.net/afs/${padded}.mp3`;
}

/**
 * Returns ayah-by-ayah audio url from EveryAyah CDN
 */
export function getAyahAudioUrl(folder: string, surahNumber: number, ayahNumber: number): string {
  const sPadded = String(surahNumber).padStart(3, '0');
  const aPadded = String(ayahNumber).padStart(3, '0');
  return `https://everyayah.com/data/${folder}/${sPadded}${aPadded}.mp3`;
}
